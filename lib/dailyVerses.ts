/**
 * Retorna o versículo bíblico correspondente a uma data específica.
 * Calcula de forma determinística pelo dia do ano, garantindo um versículo NOVO a cada dia.
 */
export function getDailyVerse(dateStr?: string): DailyVerse {
  try {
    const targetDate = dateStr ? new Date(`${dateStr}T12:00:00`) : new Date();
    // Cálculo do dia do ano (1 a 366)
    const start = new Date(targetDate.getFullYear(), 0, 0);
    const diff = targetDate.getTime() - start.getTime();
    const oneDay = 1000 * 60 * 60 * 24;
    const dayOfYear = Math.floor(diff / oneDay);

    const index = Math.abs((dayOfYear + targetDate.getFullYear() * 7) % DAILY_VERSES.length);
    return DAILY_VERSES[index] || DAILY_VERSES[0];
  } catch {
    return DAILY_VERSES[0];
  }
}
